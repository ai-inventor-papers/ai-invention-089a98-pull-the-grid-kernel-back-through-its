def prepare(regime: str = "2.0", cache: bool = True, verbose: bool = True) -> dict:
    """Load and certify data, build the feeder, cache all fold-independent operators."""
    t0 = time.time()
    checks: dict = {"withheld": True}

    # ---- environment
    import platform

    import scipy
    import networkx

    checks["versions"] = {
        "python": platform.python_version(), "numpy": np.__version__,
        "scipy": scipy.__version__, "networkx": networkx.__version__,
        "pandas": __import__("pandas").__version__,
    }
    import pandapower
    checks["versions"]["pandapower"] = pandapower.__version__
    np.show_config() if False else None
    checks["blas"] = _blas_vendor()

    # ---- T0 data certification
    pilot, regenerated = data_dir(PILOT)
    checks["data"] = certify_data(pilot)

    # ---- T1 toy unit test
    checks["toy"] = toy_identity_test()

    # ---- Step 2 feeder + targets
    ph = Physics()
    checks["feeder"] = certify_feeder(ph)
    far, s15 = ph.sheet(15)
    assert np.array_equal(s15, np.load(pilot / "sheet15.npy"))
    phase = np.load(pilot / "ph_true.npy")

    X = np.load(pilot / f"ens_s{regime}_X.npy")
    Y = np.load(pilot / f"ens_s{regime}_Y.npy")
    checks["regime"] = regime

    # ---- fold-independent operators (deterministic functions of x alone; no labels)
    t1 = time.time()
    V0b = ph.noload_voltage(s15)
    Vp1 = ph.lindist(X, s15, order=1, v0bus=V0b)
    Vp2 = ph.lindist(X, s15, order=2, v0bus=V0b)
    checks["lindist_seconds"] = time.time() - t1
    checks["noload_abs_range"] = [float(np.abs(V0b).min()), float(np.abs(V0b).max())]
    checks["lindist_raw_rmse"] = {
        "order1": float(np.sqrt(((Vp1 - Y) ** 2).mean())),
        "order2": float(np.sqrt(((Vp2 - Y) ** 2).mean())),
        "ysd": float(Y.std(0).mean()),
    }
    checks["ac_solves_each_arm"] = {
        "spectral_embedding (R1-R4, SP-*)": 0,
        "b1_rbf / b2_hop / b3_kirchhoff / b4_ridge": 0,
        "b5_lindist": 1,
        "ground truth (reused, not charged)": 220,
        "note": ("b5 needs ONE no-load runpp_3ph solve for its reference V0b and then "
                 "propagates analytically; the 220 solves are the ground truth archive, "
                 "shared by every arm and not attributable to any of them."),
    }

    # ---- Laplacian + spectra
    if cache and (OUT / "spectra_cache.npz").exists():
        ops = _load_cached(ph)
        checks["spectra_cache_hit"] = True
    else:
        ops = FeederOps.build(ph, verbose=verbose)
        ops.save_cache(OUT / "spectra_cache.npz")
        checks["spectra_cache_hit"] = False
    checks["laplacian"] = {k: v for k, v in ops.checks.items()
                           if k not in ("re_lam_smallest_45", "im_lam_frac_smallest_45",
                                        "eig_argmax_entries_45")}
    checks["laplacian"]["re_lam_smallest_45"] = ops.checks["re_lam_smallest_45"]
    checks["laplacian"]["im_over_lam_smallest_45"] = ops.checks["im_lam_frac_smallest_45"]
    checks["laplacian"]["sign_phase_argmax_entries_45"] = ops.checks["eig_argmax_entries_45"]
    checks["routes"] = {k: {"available": r.F is not None, "note": r.note,
                            "imfrac": r.imfrac} for k, r in ops.routes.items()}
    checks["gather"] = gather_check(ops, ph)

    # ---- step 14(ii): eigh/eigvalsh/eigsh are wrong on Lg, measured
    checks["hermiticity_probe"] = ops.hermiticity_probe()

    # ---- b2/b3 metrics
    Mhop = _hop_metric(ph)
    M110 = admittance_metric(ops.Zll, phase, ph.Sb)
    Zll_p = ops.Zll
    Kc_p = -Zll_p / (ph.Sb * np.conj(1.05 * np.exp(1j * np.array([0.0, -2 * np.pi / 3, 2 * np.pi / 3]))[phase]))[None, :]
    M55 = (Kc_p.conj().T @ Kc_p).real
    M55 = 0.5 * (M55 + M55.T)
    checks["metrics"] = {
        "b2_hop_max": float(Mhop.max()),
        "b3_M110_eig_min": float(np.linalg.eigvalsh(M110).min()),
        "b3_M110_eig_max": float(np.linalg.eigvalsh(M110).max()),
        "b3_M110_cond": float(np.linalg.cond(M110)),
        "b3p_M55_eig_min": float(np.linalg.eigvalsh(M55).min()),
        "b3p_M55_eig_max": float(np.linalg.eigvalsh(M55).max()),
        "circularity": ("b3 (admittance multiphase Kirchhoff metric) is derived from the "
                        "same block Laplacian the candidate's spectrum comes from and is "
                        "therefore NOT an independent baseline. b1, b2, b4 and b5 are all "
                        "constructible without that Laplacian or the treatment operator."),
    }

    # ---- folds
    fold_list, counts, per_scheme = enumerate_folds()
    checks["fold_counts"] = {str(k): v for k, v in counts.items()}
    checks["fold_counts_per_scheme"] = per_scheme
    checks["fold_counts_expected"] = {str(k): v for k, v in EXPECTED_COUNTS.items()}
    checks["fold_counts_match"] = bool(counts == EXPECTED_COUNTS)
    assert counts == EXPECTED_COUNTS, counts
    checks["fold_note"] = (
        "reserving seeds 12-29 reserves SPLITS and not data: the same 220 AC draws underlie "
        "every fold. The genuinely untouched evidence is the 2.6x regime and the moved-phase "
        "feeder, not the seed list. Realized folds are 24 at n<=80 and 12 at n=160, so the "
        "n=160 worst-fold statistic rests on 12 folds.")

    checks["timing"] = {"prepare_seconds": time.time() - t0}
    return dict(ph=ph, ops=ops, X=X, Y=Y, s15=s15, Vp1=Vp1, Vp2=Vp2, M110=M110, M55=M55,
                Mhop=Mhop, phase=phase, checks=checks, folds=fold_list, counts=counts)


def _blas_vendor() -> str:
    """Best-effort BLAS identification; the eigenvector convention is recorded separately
    because it, not the vendor string, is what makes the spectrum reproducible."""
    try:
        cfg = np.show_config(mode="dicts")
        blas = cfg.get("Build Dependencies", {}).get("blas", {})
        name = blas.get("name", "")
        return f"{name}:{blas.get('version', '')}" if name else "not reported"
    except Exception:                             # noqa: BLE001 - recorded, never fatal
        return "not reported by this numpy build"


def _hop_metric(ph: Physics) -> np.ndarray:
    from feeder import _lca_depth_table
    Dl = _lca_depth_table(ph)
    lidx = np.array([ph.bidx[int(b)] for b in ph.lbus])
    return Dl[np.ix_(lidx, lidx)].astype(float)


def _load_cached(ph: Physics) -> FeederOps:
    """Rebuild the cheap pieces and reload the cached spectra (never re-run zgeev)."""
    z = np.load(OUT / "spectra_cache.npz")
    meta = json.loads((OUT / "spectra_cache.json").read_text())
    buses = ph.buses
    idx = {b: i for i, b in enumerate(buses)}
    M = len(buses)
    src = idx[1]
    keep = np.array([i for i in range(3 * M) if i not in (3 * src, 3 * src + 1, 3 * src + 2)])
    gmap = np.full(3 * M, -1, dtype=np.int64)
    gmap[keep] = np.arange(len(keep))
    lidx = np.array([idx[int(b)] for b in ph.lbus])
    from feeder import Route
    routes = {}
    for name in ("R1", "R2", "R3", "R4", "R5"):
        F = z[f"F_{name}"] if f"F_{name}" in z.files else None
        lam = z[f"lam_{name}"] if f"lam_{name}" in z.files else None
        res = z[f"resid_{name}"] if f"resid_{name}" in z.files else None
        vra = z[f"Vraw_{name}"] if f"Vraw_{name}" in z.files else None
        routes[name] = Route(name, F, lam, res, None, meta.get("route_note", ""), Vraw=vra)
    routes["R5"] = Route("R5", None, None, None, None,
                         "UNAVAILABLE: no real diagonal D makes D Lg D^-1 Hermitian")
    ops = FeederOps(ph=ph, Lg=np.zeros((1, 1), dtype=complex), Zk=np.zeros((1, 1), dtype=complex),
                    Dl=np.zeros((1, 1), dtype=np.int32), gmap=gmap, lidx=lidx,
                    gather=z["gather"], Zll=z["Zll"], checks=meta)
    ops.routes = routes
    ops.eig_full = (None, None, 0.0)
    return ops


# --------------------------------------------------------------------------- sweep
def run_all(prep: dict, out_path: Path, lgrid=None, sizes=SIZES, verbose: bool = True,
            collect_calibrations_at=(10, 80)) -> dict:
    ops, ph = prep["ops"], prep["ph"]
    X, Y = prep["X"], prep["Y"]
    Vp1, Vp2, M110, M55, Mhop = prep["Vp1"], prep["Vp2"], prep["M110"], prep["M55"], prep["Mhop"]

    per_fold: list[dict] = []
    t0 = time.time()
    for i, (n, seed, scheme, tr, te) in enumerate(prep["folds"]):
        if n not in sizes:
            continue
        rec = run_fold(ops, ph, X, Y, tr, te, Vp1, Vp2, M110, M55, Mhop,
                       lgrid=lgrid, collect_calibrations=(n in collect_calibrations_at))
        rec.update({"n": int(n), "seed": int(seed), "scheme": int(scheme)})
        per_fold.append(rec)
        if verbose and (i % 6 == 0 or i == len(prep["folds"]) - 1):
            hl = rec["cells"].get(HEADLINE_ARM, {})
            print(f"[{i+1}/{len(prep['folds'])}] n={n:3d} s={seed:2d} p={scheme} "
                  f"meanpredict {rec['mean_predictor_nrmse']:.3f} "
                  f"best_base {rec['best_baseline']} {rec['best_baseline_nrmse']:.4f} "
                  f"headline {hl.get('nrmse', float('nan')):.4f} "
                  f"margin {100*hl.get('margin_vs_best_baseline', float('nan')):+.1f}% "
                  f"({time.time()-t0:.0f}s)", flush=True)
        if i % 12 == 0:
            out_path.write_text(json.dumps({"per_fold": per_fold}, indent=1))
    out_path.write_text(json.dumps({"per_fold": per_fold}, indent=1))
    return {"per_fold": per_fold, "seconds": time.time() - t0}


# --------------------------------------------------------------------------- aggregation
def summarise(per_fold: list[dict], sizes=SIZES) -> dict:
    arms = sorted({a for r in per_fold for a in r["cells"]})
    out: dict = {}
    for n in sizes:
        rows = [r for r in per_fold if r["n"] == n]
        if not rows:
            continue
        rec: dict = {"n_folds": len(rows)}
        # baselines
        rec["baselines"] = {}
        for b in BASELINE_NAMES:
            e = np.array([r["baselines"][b]["nrmse"] for r in rows])
            rec["baselines"][b] = {"mean": float(e.mean()), "worst": float(e.max()),
                                   "min": float(e.min()), "per_fold": e.tolist()}
        rec["mean_predictor"] = {
            "mean": float(np.mean([r["mean_predictor_nrmse"] for r in rows])),
            "per_fold": [r["mean_predictor_nrmse"] for r in rows]}
        rec["best_baseline_freq"] = {}
        for r in rows:
            rec["best_baseline_freq"][r["best_baseline"]] = \
                rec["best_baseline_freq"].get(r["best_baseline"], 0) + 1
        rec["best_independent_freq"] = {}
        for r in rows:
            rec["best_independent_freq"][r["best_independent_baseline"]] = \
                rec["best_independent_freq"].get(r["best_independent_baseline"], 0) + 1
        # arms
        rec["arms"] = {}
        for a in arms:
            cells = [r["cells"].get(a) for r in rows]
            ok = [c for c in cells if c and "nrmse" in c]
            if not ok:
                rec["arms"][a] = {"status": cells[0].get("status") if cells and cells[0] else "missing",
                                  "n_folds": 0}
                continue
            e = np.array([c["nrmse"] for c in ok])
            mg = np.array([c["margin_vs_best_baseline"] for c in ok])
            mi = np.array([c["margin_vs_best_independent"] for c in ok])
            rt = np.array([c["ratio_to_mean"] for c in ok])
            nl = np.array([c["nlpd"] for c in ok if c["nlpd"] is not None])
            c68 = np.array([c["cov68"] for c in ok if c["cov68"] is not None])
            c95 = np.array([c["cov95"] for c in ok if c["cov95"] is not None])
            each = {b: [c["margin_vs_each"][b] for c in ok] for b in BASELINE_NAMES}
            rec["arms"][a] = {
                "n_folds": len(ok),
                "mean_far_end_rmse": float(e.mean()),
                "worst_fold_far_end_rmse": float(e.max()),
                "min_fold_far_end_rmse": float(e.min()),
                "std_far_end_rmse": float(e.std()),
                "mean_rmse_over_mean_predictor": float(rt.mean()),
                "max_rmse_over_mean_predictor": float(rt.max()),
                "mean_margin_vs_best_baseline": float(mg.mean()),
                "worst_fold_margin": float(mg.min()),
                "best_fold_margin": float(mg.max()),
                "std_margin": float(mg.std()),
                "frac_folds_clearing_20pct": float(np.mean(mg >= 0.20)),
                "mean_margin_vs_best_independent": float(mi.mean()),
                "worst_fold_margin_vs_best_independent": float(mi.min()),
                "mean_nlpd": float(nl.mean()) if nl.size else None,
                "mean_coverage68": float(c68.mean()) if c68.size else None,
                "mean_coverage95": float(c95.mean()) if c95.size else None,
                "frac_coverage68_within_005": float(np.mean(np.abs(c68 - 0.68) <= 0.05)) if c68.size else None,
                "margin_vs_each_baseline_mean": {b: float(np.mean(v)) for b, v in each.items()},
                "margin_vs_each_baseline_worst": {b: float(np.min(v)) for b, v in each.items()},
                "per_fold_nrmse": e.tolist(),
                "per_fold_margin": mg.tolist(),
                "per_fold_margin_independent": mi.tolist(),
                "per_fold_nlpd": nl.tolist(),
                "per_fold_cov68": c68.tolist(),
                "per_fold_cov95": c95.tolist(),
                "per_fold_hyper": [c["hyper"] for c in ok],
                "k": ok[0]["k"], "route": ok[0]["route"], "variant": ok[0]["variant"],
                "scaling": ok[0]["scaling"],
            }
        out[n] = rec
    return out
